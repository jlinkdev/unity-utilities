"""Distribute the optional Editor bootstrap to independently installable utility packages."""
import json
from pathlib import Path
import re
import uuid


PACKAGES = Path(__file__).resolve().parents[1] / "Packages"
PILOT = PACKAGES / "com.jlinkdev.object-highlighting" / "Editor"
FRAMEWORK = "com.jlinkdev.sample-framework"


def sources():
    helper = (PILOT / "SampleFrameworkInstaller.cs").read_text(encoding="utf-8")
    version = json.loads((PACKAGES / FRAMEWORK / "package.json").read_text())["version"]
    for package in sorted(PACKAGES.glob("com.jlinkdev.*")):
        if not package.is_dir() or package.name == FRAMEWORK:
            continue
        manifest = json.loads((package / "package.json").read_text(encoding="utf-8-sig"))
        if not manifest.get("samples"):
            continue
        editor = package / "Editor"
        if editor != PILOT:
            yield editor / "SampleFrameworkInstaller.cs", helper
        title = manifest["displayName"].removeprefix("jlinkdev ")
        samples = manifest["samples"]
        names = samples[0]["displayName"] if len(samples) == 1 else title + " samples"
        markers = []
        for sample in samples:
            meta = (package / sample["path"] / "README.md.meta").read_text()
            guid = re.search(r"^guid: ([0-9a-f]{32})", meta, re.M)[1]
            markers.append(f'            {{ {json.dumps(sample["displayName"])}, "{guid}" }},')
        rows = "\n".join(markers)
        yield editor / "SampleFrameworkSettings.cs", f'''// Generated by scripts/sample_installers.py from the registered samples.
using System.Collections.Generic;

namespace jlinkdev.SampleInstallation
{{
    internal static class SampleFrameworkSettings
    {{
        internal const string PackageId = "{FRAMEWORK}";
        internal const string Version = "{version}";
        internal const string GitRepository = "https://github.com/jlinkdev/unity-utilities.git?path=/Packages/{FRAMEWORK}";
        internal const string GitRevision = "sample-framework-v{version}";
        internal const string Menu = {json.dumps(f"Tools/jlinkdev/{title}/Install Sample Framework")};
        internal const string SampleName = {json.dumps(names)};
        internal static readonly Dictionary<string, string> Samples = new Dictionary<string, string>
        {{
{rows}
        }};
    }}
}}
'''
        if not list(editor.glob("*.asmdef")):
            assembly = manifest["name"] + ".SampleInstaller.Editor"
            yield editor / (assembly + ".asmdef"), json.dumps({
                "name": assembly, "includePlatforms": ["Editor"], "autoReferenced": False
            }, indent=2) + "\n"


def ensure_meta(path):
    meta = Path(str(path) + ".meta")
    if meta.exists():
        return
    guid = uuid.uuid5(uuid.NAMESPACE_URL, path.relative_to(PACKAGES).as_posix()).hex
    data = f"fileFormatVersion: 2\nguid: {guid}\n"
    if path.is_dir():
        data += "folderAsset: yes\nDefaultImporter:\n  externalObjects: {}\n"
    elif path.suffix == ".asmdef":
        data += "AssemblyDefinitionImporter:\n  externalObjects: {}\n"
    meta.write_text(data, encoding="utf-8")


if __name__ == "__main__":
    for path, content in sources():
        path.parent.mkdir(exist_ok=True)
        ensure_meta(path.parent)
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
        ensure_meta(path)
